// Python 관례: 어느 폴더가 프로젝트 뿌리이고, 어느 파일이 생성된 코드·빌드 산출물·가상 환경이고 어느 파일이 테스트인지,
// 모듈 이름(import 대상)을 어느 파일로 푸는지. 정밀 어댑터(python.ts, python-refine.ts)와 추정 규칙(src/inferred/python.ts)이 같은 규칙을 써요.
import { posix } from 'node:path';
import type { FileRole } from '../facts.ts';
import { hasGeneratedMark } from './conventions.ts';

/** 이 파일이 있는 폴더를 Python 프로젝트 뿌리로 봐요. scip-python은 뿌리마다 한 번 돌아요. */
const PROJECT_MARKERS = ['pyproject.toml', 'setup.py', 'setup.cfg', 'requirements.txt', 'Pipfile'];
/** 경로에 이 폴더가 끼어 있으면 빌드 산출물, 가상 환경, 캐시예요. */
const SKIPPED_DIRS = new Set(['build', 'dist', '__pycache__', 'venv', 'site-packages', 'node_modules']);
/** protoc 등이 만드는 파일의 꼬리. */
const GENERATED_SUFFIXES = ['_pb2.py', '_pb2_grpc.py'];
/** 생성기가 파일 머리에 다는 표시(protoc의 `DO NOT EDIT!`, `@generated`, Django 등의 `# Generated by`). */
const GENERATED_MARK = /DO NOT EDIT|@generated|^# *Generated by/m;
/** 이 이름의 폴더 아래는 테스트예요. */
const TEST_DIRS = new Set(['test', 'tests']);

export const ownsPython = (path: string) => path.endsWith('.py');

/** 숨김 폴더나 빌드·가상 환경 폴더 안인지. */
function underSkippedDir(path: string): boolean {
  return path
    .split('/')
    .slice(0, -1)
    .some((part) => part.startsWith('.') || SKIPPED_DIRS.has(part));
}

/**
 * 생성된 코드, 빌드 산출물, 가상 환경 안의 파일인지.
 * @param head 파일 머리 글(앞 1000자면 충분해요). 읽지 못하면 빈 글.
 */
export function isExcludedPython(path: string, head: string): boolean {
  if (underSkippedDir(path)) return true;
  if (GENERATED_SUFFIXES.some((s) => path.endsWith(s))) return true;
  return hasGeneratedMark(head, GENERATED_MARK);
}

/** 테스트 파일인지: test/·tests/ 폴더 아래, 또는 이름이 test_*.py, *_test.py, conftest.py. */
export function pythonRole(path: string): FileRole {
  const parts = path.split('/');
  const name = parts.at(-1)!;
  if (parts.slice(0, -1).some((p) => TEST_DIRS.has(p))) return 'test';
  return name.startsWith('test_') || name.endsWith('_test.py') || name === 'conftest.py' ? 'test' : 'app';
}

/**
 * Python 프로젝트 뿌리(저장소 기준, '' = 뿌리). 표시 파일(pyproject.toml, requirements.txt 등)이 있는 폴더 가운데
 * 다른 뿌리 안에 들지 않은 것. 표시 파일이 하나도 없으면 저장소 뿌리 하나예요.
 * 숨김 폴더와 빌드·가상 환경 폴더 안의 표시 파일은 보지 않아요.
 */
export function pythonProjects(files: Iterable<string>): string[] {
  const dirs = new Set<string>();
  for (const f of files) {
    const name = f.split('/').at(-1)!;
    if (!PROJECT_MARKERS.includes(name) || underSkippedDir(f)) continue;
    dirs.add(posix.dirname(f) === '.' ? '' : posix.dirname(f));
  }
  if (dirs.size === 0) return [''];
  const sorted = [...dirs].sort((a, b) => a.length - b.length);
  const outer: string[] = [];
  for (const d of sorted) if (!outer.some((o) => o === '' || d.startsWith(`${o}/`))) outer.push(d);
  return outer.sort();
}

/** 파일이 든 프로젝트 뿌리. 어느 뿌리에도 들지 않으면 null. */
export function projectOf(path: string, projects: string[]): string | null {
  return projects.filter((p) => p === '' || path.startsWith(`${p}/`)).sort((a, b) => b.length - a.length)[0] ?? null;
}

/**
 * import의 모듈 이름을 저장소 안 파일로 풀어요. 밖(표준 라이브러리, 설치한 패키지)이면 null.
 * - 상대(`.cart`, `..util.x`, `.`): 파일의 폴더에서 점 하나 빼고 하나마다 한 칸 올라가요.
 * - 절대(`shop.cart`): 프로젝트 뿌리, 그 아래 src/, 파일의 폴더, 저장소 뿌리 순서로 찾아요.
 * 모듈 `a.b`는 `a/b.py` 또는 `a/b/__init__.py`예요.
 */
export function resolvePythonModule(fromPath: string, spec: string, files: ReadonlySet<string>, projects: string[]): string | null {
  const dots = /^\.*/.exec(spec)![0].length;
  const parts = spec.slice(dots).split('.').filter(Boolean);
  const at = (base: string): string | null => {
    const stem = posix.join(base, ...parts);
    const candidates = parts.length === 0 ? [posix.join(base, '__init__.py')] : [`${stem}.py`, posix.join(stem, '__init__.py')];
    for (const c of candidates) {
      const path = posix.normalize(c).replace(/^\.\//, '');
      if (!path.startsWith('../') && files.has(path)) return path;
    }
    return null;
  };
  const dir = posix.dirname(fromPath) === '.' ? '' : posix.dirname(fromPath);
  if (dots > 0) {
    let base = dir;
    for (let i = 1; i < dots; i++) base = posix.dirname(base) === '.' ? '' : posix.dirname(base);
    return at(base);
  }
  const project = projectOf(fromPath, projects) ?? '';
  for (const base of [project, posix.join(project, 'src'), dir, '']) {
    const hit = at(base);
    if (hit) return hit;
  }
  return null;
}
