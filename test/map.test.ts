// 코드 지도(map): 모듈 구조가 있는 예제 저장소를 색인하고 명령줄 `map`으로 HTML을 그려,
// HTML에 든 자료가 정답과 같은지 봐요. 화면의 생김새(그리는 코드)는 시험하지 않아요. 브라우저로 띄워 확인해요.
import assert from 'node:assert/strict';
import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, before, describe, it } from 'node:test';
import { expected, indexFixture, runCliRaw, type IndexedFixture } from './harness.ts';

// check 예제(modular_sample)에 지도만 보는 것을 더해요: 외부 패키지(meta), barrel, 테스트 파일.
// check 정답이 바뀌지 않도록 예제 자체는 그대로 두고 사본에만 더해요.
const EXTRA: Record<string, string> = {
  'pubspec.yaml': [
    'name: modular_sample',
    'description: code-atlas check 테스트용 예제. 기능 폴더(모듈)가 서로 기대는 작은 Dart 앱이에요.',
    'publish_to: none',
    'version: 1.0.0',
    'environment:',
    '  sdk: ^3.5.0',
    'dependencies:',
    '  meta: 1.19.0',
    '',
  ].join('\n'),
  'pubspec.lock': [
    '# Generated by pub',
    '# See https://dart.dev/tools/pub/glossary#lockfile',
    'packages:',
    '  meta:',
    '    dependency: "direct main"',
    '    description:',
    '      name: meta',
    '      sha256: "307249ce4ff29d58a18e97f6345f539382eb9c9c29ecda628900f31de0443dd9"',
    '      url: "https://pub.dev"',
    '    source: hosted',
    '    version: "1.19.0"',
    'sdks:',
    '  dart: ">=3.5.0 <4.0.0"',
    '',
  ].join('\n'),
  // 외부 패키지를 import하는 파일.
  'lib/shared/money.dart': "import 'package:meta/meta.dart';\n\n@immutable\nclass Money {\n  const Money(this.won);\n  final int won;\n}\n",
  // 다시 내보내는 파일(barrel). 테스트는 이것을 거쳐 strings.dart의 title만 써요. header.dart의 이름은 쓰지 않아요.
  'lib/shared/shared.dart': "export 'header.dart';\nexport 'strings.dart';\n",
  'test/strings_test.dart': "import 'package:modular_sample/shared/shared.dart';\n\nvoid main() {\n  print(title('a'));\n}\n",
  // 직접 import하는 테스트.
  'test/order_status_test.dart':
    "import 'package:modular_sample/features/orders/order_status.dart';\n\nvoid main() {\n  print(announce(OrderStatus.placed));\n}\n",
};

const DATA = /<script type="application\/json" id="code-map-data">([\s\S]*?)<\/script>/;

/** 그린 HTML에서 화면에 넣은 자료를 꺼내요. */
function dataOf(html: string): any {
  const m = DATA.exec(html);
  assert.ok(m, 'HTML에 code-map-data 자료가 있어야 해요');
  return JSON.parse(m[1]!);
}

describe('modular_sample map', () => {
  let fx: IndexedFixture;
  let work: string;
  let printed: any;
  let html: string;
  let data: any;
  const db = () => join(fx.repo, '..', 'atlas.db');
  before(() => {
    fx = indexFixture('modular_sample', { extraFiles: EXTRA });
    work = mkdtempSync(join(tmpdir(), 'code-atlas-map-'));
    const out = join(work, 'map.html');
    const r = runCliRaw(['map', '--repo', fx.repo, '--db', db(), '--out', out]);
    assert.equal(r.status, 0, r.stderr);
    printed = JSON.parse(r.stdout);
    html = readFileSync(out, 'utf8');
    data = dataOf(html);
  });
  after(() => {
    fx?.dispose();
    if (work) rmSync(work, { recursive: true, force: true });
  });

  it('명령 한 번으로 HTML이 나오고, 머리말 자료에 브랜치와 커밋이 있다', () => {
    assert.equal(printed.out, join(work, 'map.html'));
    assert.equal(printed.indexed, false, '색인이 최신이면 다시 색인하지 않아요');
    assert.equal(data.branch, 'main');
    assert.equal(data.commit, fx.head());
    assert.equal(data.head, fx.head().slice(0, 7));
    assert.match(html, /^<!doctype html>/);
    assert.equal(fx.gitStatus(), '', '그리기는 저장소를 바꾸지 않아요');
  });

  it('지도 자료가 정답과 같다(check의 답을 그대로 쓰고, 파일마다 줄 수·변경·쓰임·테스트가 붙는다)', () => {
    const { head, commit, date, ...rest } = data;
    assert.match(date, /^\d{4}-\d{2}-\d{2}$/);
    assert.deepEqual(rest, expected('modular_sample', 'map.json'));
  });

  it('테스트 열: 직접 import는 2, barrel을 거쳐 이름을 쓰면 1, barrel에만 든 파일은 0', () => {
    const t = Object.fromEntries(data.files.map((f: any) => [f.p, f.t]));
    assert.equal(t['lib/features/orders/order_status.dart'], 2);
    assert.equal(t['lib/shared/shared.dart'], 2);
    assert.equal(t['lib/shared/strings.dart'], 1);
    assert.equal(t['lib/shared/header.dart'], 0);
  });

  it('외부 패키지가 닿는 파일은 그 패키지를 import한 파일이다', () => {
    assert.deepEqual(data.pkgUse, { meta: ['lib/shared/money.dart'] });
  });

  it('색인이 없으면 먼저 색인하고 그린다', () => {
    const freshDb = join(work, 'fresh.db');
    const out = join(work, 'fresh.html');
    const r = runCliRaw(['map', '--repo', fx.repo, '--db', freshDb, '--out', out]);
    assert.equal(r.status, 0, r.stderr);
    assert.equal(JSON.parse(r.stdout).indexed, true);
    assert.ok(existsSync(freshDb));
    const { head, commit, date, ...rest } = dataOf(readFileSync(out, 'utf8'));
    assert.deepEqual(rest, expected('modular_sample', 'map.json'));
  });

  it('색인 뒤 코드가 바뀌었으면 다시 색인하고 바뀐 것을 그린다', () => {
    fx.write('lib/features/catalog/price_format.dart', "import '../../shared/money.dart';\n\nString formatPrice(int won) => '${Money(won).won}원';\n");
    try {
      const out = join(work, 'changed.html');
      const r = runCliRaw(['map', '--repo', fx.repo, '--db', db(), '--out', out]);
      assert.equal(r.status, 0, r.stderr);
      assert.equal(JSON.parse(r.stdout).indexed, true);
      const changed = dataOf(readFileSync(out, 'utf8'));
      assert.ok(changed.medges['catalog>shared'].some(([f, t]: [string, string]) => f === 'lib/features/catalog/price_format.dart' && t === 'lib/shared/money.dart'));
    } finally {
      fx.restore();
    }
  });
});
